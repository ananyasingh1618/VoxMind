#!/usr/bin/env python3
"""Evaluates the real faster-whisper STT provider (the exact class the
production audio pipeline uses) against a small, versioned dataset of
reference transcripts - see ml/evaluation/stt_datasets/stt_eval_v1.json for
the dataset and exactly how each reference_text was established
independently of any Whisper run (never generated by the model under test).

Usage:
    python -m ml.evaluation.evaluate_stt --dataset ml/evaluation/stt_datasets/stt_eval_v1.json
"""
from __future__ import annotations

import argparse
import asyncio
import json
import sys
import time
from pathlib import Path

from ml.evaluation.wer import SttSampleResult, aggregate_stt_metrics, character_error_rate, word_error_rate

TTS_SYNTHESIS_SEED = 42


async def run_evaluation(args: argparse.Namespace) -> None:
    import torch

    from voxmind.core.config import get_settings
    from voxmind.repositories.evaluation_run_repository import EvaluationRunRepository
    from voxmind.services.speech.preprocessing import preprocess_audio
    from voxmind.services.speech.whisper_provider import FasterWhisperProvider
    from voxmind.services.tts.local_hf_provider import LocalHfTtsProvider

    dataset_path = Path(args.dataset)
    dataset = json.loads(dataset_path.read_text())
    repo_root = Path(__file__).resolve().parents[2]

    settings = get_settings()
    whisper = FasterWhisperProvider(settings)
    tts = LocalHfTtsProvider(settings)

    results: list[SttSampleResult] = []
    errors: list[dict] = []

    for sample in dataset["samples"]:
        sample_id = sample["sample_id"]
        try:
            if sample["audio_source"] == "fixture":
                raw_bytes = (repo_root / sample["audio_path"]).read_bytes()
            elif sample["audio_source"] == "synthesize_at_eval_time":
                torch.manual_seed(TTS_SYNTHESIS_SEED)
                tts_result = await tts.synthesize(sample["reference_text"])
                raw_bytes = tts_result.audio_bytes
            else:
                raise ValueError(f"Unknown audio_source: {sample['audio_source']!r}")

            _metadata, wav_bytes = await preprocess_audio(raw_bytes, settings=settings)

            started = time.monotonic()
            transcription = await whisper.transcribe(wav_bytes, sample_rate=16000)
            latency_ms = round((time.monotonic() - started) * 1000)

            wer = word_error_rate(sample["reference_text"], transcription.text)
            cer = character_error_rate(sample["reference_text"], transcription.text)
            results.append(
                SttSampleResult(
                    sample_id=sample_id,
                    reference_text=sample["reference_text"],
                    hypothesis_text=transcription.text,
                    wer=wer,
                    cer=cer,
                    latency_ms=latency_ms,
                )
            )
            print(f"{sample_id}: wer={wer:.3f} cer={cer:.3f} latency_ms={latency_ms} hyp={transcription.text!r}")
        except Exception as exc:  # noqa: BLE001 - a genuine per-sample failure, recorded not swallowed
            errors.append({"sample_id": sample_id, "error": str(exc)})
            print(f"{sample_id}: FAILED - {exc}", file=sys.stderr)

    if not results:
        print("error: no samples produced a result - cannot compute STT metrics.", file=sys.stderr)
        sys.exit(1)

    metrics = aggregate_stt_metrics(results)
    status = "completed" if not errors else "partial"

    print(f"\n=== STT evaluation: {dataset['version']} ===")
    print(f"n_samples={metrics.n_samples} avg_wer={metrics.avg_wer:.4f} avg_cer={metrics.avg_cer:.4f} "
          f"avg_latency_ms={metrics.avg_latency_ms:.1f}")
    if errors:
        print(f"skipped/failed: {len(errors)} - {errors}")

    from voxmind.db.session import AsyncSessionLocal

    async with AsyncSessionLocal() as session:
        run = await EvaluationRunRepository(session).create(
            evaluation_type="stt",
            dataset_version=dataset["version"],
            model_version=f"faster-whisper:{settings.WHISPER_MODEL_SIZE}",
            configuration={
                "whisper_compute_type": settings.WHISPER_COMPUTE_TYPE,
                "whisper_device": settings.WHISPER_DEVICE,
                "tts_synthesis_seed": TTS_SYNTHESIS_SEED,
                "tts_model": settings.TTS_LOCAL_MODEL,
            },
            random_seed=TTS_SYNTHESIS_SEED,
            sample_count=metrics.n_samples,
            status=status,
            metrics=metrics.to_dict(),
            errors=errors,
            notes=(
                None if not errors else f"{len(errors)} sample(s) failed and were excluded from the aggregate."
            ),
        )
        await session.commit()
        print(f"\nPersisted EvaluationRun {run.id} (status={status}).")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dataset", default="ml/evaluation/stt_datasets/stt_eval_v1.json")
    args = parser.parse_args()
    asyncio.run(run_evaluation(args))


if __name__ == "__main__":
    main()
